"""Protect the chosen Attested brand details and prose conventions."""
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
FRONTEND=ROOT/"web"

def test_browser_tab_branding():
    head=(FRONTEND/"index.html").read_text(encoding="utf-8")
    assert "AksharaCheck | Find the letters your website breaks" in head
    assert 'href="/favicon.svg"' in head
    assert 'name="theme-color" content="#F8FAF7"' in head

def test_reference_sections_and_navigation():
    page=(FRONTEND/"src"/"main.tsx").read_text(encoding="utf-8")
    for anchor in ['id="try"','id="checks"','id="report"','id="faq"']:
        assert anchor in page
    assert "Check a line of text right here" in page
    assert "Every finding comes with its evidence" in page
    assert "https://github.com/ashh-droid/AksharaCheck" in page

def test_no_em_dash_in_user_facing_pages():
    for name in ["index.html","src/main.tsx"]:
        assert "\u2014" not in (FRONTEND/name).read_text(encoding="utf-8")
    report=(ROOT/"aksharacheck"/"report.py").read_text(encoding="utf-8")
    assert "\u2014" not in report

def test_no_two_frontends():
    assert (FRONTEND/"src"/"main.tsx").exists()
    # Built UI is generated by Vite rather than a manually maintained second app.
    assert not (FRONTEND/"src"/"legacy.js").exists()
